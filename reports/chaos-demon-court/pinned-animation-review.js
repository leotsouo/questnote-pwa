import * as summon from '/questnote-pwa-preview/src/themedSummonController.js';
import * as reveal from '/questnote-pwa-preview/src/summonRevealService.js';
import {playAwakeningScene} from '/questnote-pwa-preview/src/petAwakeningScene.js';
const manifest=await (await fetch('release-artifact.json')).json();
const {loadCatalogBundle}=await import('/questnote-pwa-preview/src/releaseCatalog.js');
const bundle=await loadCatalogBundle();
const pets=bundle.petsData.pets.filter(p=>p.poolTags.includes('darkcrown_court_release'));
const catalog=await (await fetch('data/pet-awakening.json')).json();
const pool=bundle.poolsData.pools.find(p=>p.id==='darkcrown_court_release');
const high=pets.filter(p=>['UR','SSR'].includes(p.rarity));
const fixed=()=>[...high,...pets.filter(p=>!high.includes(p)).slice(0,3)].map(pet=>({pet,rarity:pet.rarity,isNew:true}));
const escape=s=>String(s).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
document.querySelector('#artifact').textContent=manifest.artifactId;
document.querySelector('#pick').innerHTML=pets.map(p=>'<option value="'+p.id+'">'+escape(p.rarity+' '+p.name)+'</option>').join('');
document.querySelector('#pairs').innerHTML=high.map(p=>{const e=catalog.pets.find(x=>x.petId===p.id);return '<article><h2>'+escape(p.name)+'</h2><div class="pair"><img src="'+e.initialImage.card+'" alt="魔獸"><img src="'+e.awakenedImage.card+'" alt="覺醒人形"></div><button data-awake="'+p.id+'">覺醒重播</button><p>'+escape(e.signature)+'</p></article>';}).join('');
let pending=null;
const reduced=()=>document.querySelector('#reduced').checked;
const start=p=>{pending=p;window.viewer.lastResult=null;p.then(r=>window.viewer.lastResult=r??{done:true});return p;};
const entry=()=>start(summon.playPoolDebutPresentation({poolId:pool.id,poolName:pool.name,presentation:pool.presentation,reduceMotion:reduced()}));
const single=()=>{const pet=pets.find(p=>p.id===document.querySelector('#pick').value);return start(summon.playThemedSummon({animationKey:'chaos_demon_court',results:[{pet,rarity:pet.rarity,isNew:true}],reduceMotion:reduced()}));};
const ten=(skipRitual=false)=>start(summon.playThemedSummon({animationKey:'chaos_demon_court',results:fixed(),mode:'ten',skipRitual,reduceMotion:reduced()}));
const awake=id=>{const pet=pets.find(p=>p.id===id);return start(playAwakeningScene(catalog.pets.find(p=>p.petId===id),pet,{reducedMotion:reduced()}));};
window.viewer={manifest,pets,high,catalog,pool,summon,reveal,entry,single,ten,awake,fixed,lastResult:null};
document.querySelector('#entry').onclick=entry;
document.querySelector('#switch').onclick=entry;
document.querySelector('#single').onclick=single;
document.querySelector('#ten').onclick=()=>ten();
document.querySelector('#pairs').onclick=e=>{const id=e.target.dataset.awake;if(id)awake(id);};

